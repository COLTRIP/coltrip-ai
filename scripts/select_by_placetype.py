loader = RealDataLoader()
all_pois = loader.fetch_pois()
by_name = {p.name: p for p in all_pois}

anchors = [by_name[n] for n in ["전포공구길", "부산시민공원", "서면먹자골목", "삼광사"] if n in by_name]
center_lat = sum(p.lat for p in anchors) / len(anchors)
center_lng = sum(p.lng for p in anchors) / len(anchors)

by_placetype = defaultdict(list)
for name in CONFIRMED_NAMES:
    p = by_name.get(name)
    if not p:
        continue
    placetype = CATEGORY_TO_PLACETYPE.get(p.category)
    if not placetype:
        continue
    dist = haversine_km(center_lat, center_lng, p.lat, p.lng)
    by_placetype[placetype].append((p.name, p.category, dist))

for pt in ["CAFE", "NATURE", "CULTURE", "ALLEY", "TEMPLE", "EXPERIENCE", "BOOK", "BEACH"]:
    items = sorted(by_placetype[pt], key=lambda x: x[2])
    print(f"\n[{pt}] 후보 {len(items)}개 (가까운 순)")
    for name, cat, dist in items[:6]:
        print(f"   {name} ({cat}) - {dist:.2f}km")